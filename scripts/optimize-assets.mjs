import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

async function walk(dir) {
  return (await Promise.all((await fs.readdir(dir, { withFileTypes: true })).map(entry =>
    entry.isDirectory() ? walk(`${dir}/${entry.name}`) : `${dir}/${entry.name}`))).flat();
}

const files = await walk('src');
const sources = files.filter(file => /\.(tsx?|scss)$/.test(file));
const text = (await Promise.all(sources.map(file => fs.readFile(file, 'utf8')))).join('\n');
const output = 'src/shared/assets/responsive';
await fs.mkdir(output, { recursive: true });
const imports = [];
const entries = [];
const replacements = {};
let before = 0;
let after = 0;
let count = 0;
for (const file of files.filter(file => /\.jpe?g$/i.test(file))) {
  if (!text.includes(path.basename(file))) continue;
  const input = await fs.readFile(file);
  const metadata = await sharp(input).metadata();
  const widths = [...new Set([320, 960, 1600, Math.min(metadata.width, 2400)].filter(width => width <= metadata.width))].sort((a, b) => a - b);
  const names = [];
  for (const width of widths) {
    const dest = `${output}/${count}-${width}.webp`;
    await sharp(input).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 82 }).toFile(dest);
    const name = `image${count}_${width}`;
    imports.push(`import ${name} from './responsive/${count}-${width}.webp';`);
    names.push(`${name} + ' ${width}w'`);
    after += (await fs.stat(dest)).size;
  }
  imports.push(`import original${count} from '${path.relative('src/shared/assets', file).replaceAll('\\', '/').replace(/^(?!\.)/, './')}';`);
  replacements[file] = `${output}/${count}-${widths.at(-1)}.webp`;
  entries.push(`[original${count}]: { srcSet: [${names.join(', ')}].join(', '), width: ${metadata.width}, height: ${metadata.height} }`);
  before += input.length;
  count++;
}
await fs.writeFile('src/shared/assets/image-sources.ts', `// Generated by npm run optimize:assets.\n${imports.join('\n')}\nexport const imageSources: Record<string, { srcSet: string; width: number; height: number }> = {\n${entries.join(',\n')}\n};\n`);
await fs.writeFile('src/shared/assets/image-map.json', JSON.stringify(replacements, null, 2) + '\n');

// Keep only Japanese unicode chunks used by current content, and only WOFF2.
const japanese = [...new Set([...text].map(char => char.codePointAt(0)).filter(code => code >= 0x3000))];
let fonts = '';
for (const weight of [400, 700]) {
  const css = await fs.readFile(`node_modules/@fontsource/noto-sans-jp/${weight}.css`, 'utf8');
  for (const block of css.match(/@font-face\s*\{[^}]+\}/g) ?? []) {
    const ranges = [...block.matchAll(/U\+([0-9a-f]+)(?:-([0-9a-f]+))?/gi)];
    if (!ranges.some(([, lo, hi]) => japanese.some(code => code >= parseInt(lo, 16) && code <= parseInt(hi ?? lo, 16)))) continue;
    fonts += block.replace(/, url\([^)]*\.woff\) format\('woff'\)/g, '').replaceAll('./files/', '../../../node_modules/@fontsource/noto-sans-jp/files/') + '\n';
  }
}
await fs.writeFile('src/app/styles/japanese-fonts.css', `/* Generated by npm run optimize:assets after changing Japanese content. */\n${fonts}`);
console.log(`${count} images: originals ${(before / 1e6).toFixed(1)} MB; all responsive variants ${(after / 1e6).toFixed(1)} MB.`);
